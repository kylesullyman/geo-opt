"""Proposed robots.txt: keep the site's existing rules, and guarantee every
answer-time retrieval bot is allowed. Training bots follow client.yaml's
training_bots policy (unchanged | allow | block)."""

from __future__ import annotations

from geo.bots import RETRIEVAL, TRAINING
from geo.config import Client
from geo.fixes import Artifact, generator
from geo.robots import Robots, RobotsGroup, Rule, render


@generator("robots")
def generate(client: Client, current_robots: str | None, sitemap_url: str | None = None) -> Artifact:
    base = Robots.parse(current_robots or "")
    notes: list[str] = []
    retrieval_tokens = {b.token.lower() for b in RETRIEVAL}
    training_tokens = {b.token.lower() for b in TRAINING}
    policy = client.config.training_bots

    kept: list[RobotsGroup] = []
    for g in base.groups:
        agents = []
        for a in g.agents:
            t = a.split("/")[0].strip().lower()
            if t in retrieval_tokens:
                notes.append(f"removed '{a}' from group at line {g.start_line}; retrieval bots get an explicit allow group")
                continue
            if t in training_tokens and policy != "unchanged":
                notes.append(f"removed '{a}' from group at line {g.start_line}; training policy is '{policy}'")
                continue
            agents.append(a)
        if agents:
            kept.append(RobotsGroup(agents=agents, rules=g.rules, start_line=g.start_line))

    # If '*' has a site-wide disallow, retrieval bots need their own group to escape it.
    # We always emit one: explicit is auditable.
    out_groups = [
        RobotsGroup(agents=[b.token for b in RETRIEVAL], rules=[Rule(allow=True, pattern="/", line=0)])
    ]
    star_rules, _ = base.rules_for("*")
    private = [r for r in star_rules if not r.allow and r.pattern not in ("/", "/*")]
    if private:
        # Preserve genuinely private paths (e.g. /wp-admin/) for retrieval bots too.
        out_groups[0].rules.extend(Rule(allow=False, pattern=r.pattern, line=0) for r in private)
        notes.append(f"kept {len(private)} private-path Disallow rule(s) from '*' for retrieval bots")

    if policy == "allow":
        out_groups.append(
            RobotsGroup(agents=[b.token for b in TRAINING], rules=[Rule(allow=True, pattern="/", line=0)])
        )
    elif policy == "block":
        out_groups.append(
            RobotsGroup(agents=[b.token for b in TRAINING], rules=[Rule(allow=False, pattern="/", line=0)])
        )
    out_groups.extend(kept)

    sitemaps = list(dict.fromkeys(base.sitemaps + ([sitemap_url] if sitemap_url else [])))
    header = [
        f"Proposed robots.txt for {client.config.domain}. Generated by geo; review before publishing.",
        "Answer-time AI retrieval bots are explicitly allowed (this controls what AI can say about the business now).",
        f"Training bots: {policy}.",
    ]
    content = render(out_groups, sitemaps, header=header)

    # Verify the proposal actually does what it claims before a human sees it.
    check = Robots.parse(content)
    failures = [b.token for b in RETRIEVAL if not check.allowed(b.token, "/")]
    if policy == "block":
        failures += [f"{b.token} (should be blocked)" for b in TRAINING if check.allowed(b.token, "/")]
    return Artifact(
        filename="robots.txt",
        content=content,
        ready=not failures,
        validation={"ok": not failures, "failures": failures},
        notes=notes,
    )
